def choose_tool(question):

    question = question.lower()

    if "what" in question:
        return "wikipedia"

    elif "who" in question:
        return "wikipedia"

    elif "when" in question:
        return "wikipedia"

    elif "where" in question:
        return "wikipedia"

    elif "explain" in question:
        return "wikipedia"

    else:
        return "wikipedia"